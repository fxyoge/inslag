//! Test your Bevy game headlessly with Luau scenarios and player input.
//!
//! Add your production plugins to a [`Suite`], set up fixtures in Luau, then
//! exercise the game through keyboard, mouse, or gamepad input. No display or GPU
//! is needed.
//!
//! # Connect the test runner
//!
//! Add `inslag_e2e` as a dev-dependency and `inslag_e2e_build` as a build-dependency.
//! In `build.rs`, call `inslag_e2e_build::discover()` from `main`.
//!
//! In `tests/e2e.rs`:
//!
//! ```no_run
//! use bevy::prelude::*;
//! use inslag_e2e::Suite;
//! use inslag_persist::SavePlugin;
//! use inslag_state_tree::StateTreePlugin;
//!
//! fn run(path: &str) {
//!     Suite::new(env!("CARGO_MANIFEST_DIR"), |app, writable| {
//!         app.add_plugins((
//!             StateTreePlugin::new(Update),
//!             SavePlugin::sqlite(writable.join("save.sqlite")),
//!         ));
//!     })
//!     .run(path);
//! }
//! ```
//!
//! Use your game's production plugin list in the callback. The harness supplies
//! Bevy's platform plugins; don't add `DefaultPlugins` again. Use `writable` for
//! saves and other test output: each scenario gets a fresh temporary directory.
//!
//! At the bottom of that test file, include the tests generated by your build script:
//!
//! ```ignore
//! include!(concat!(env!("OUT_DIR"), "/e2e_cases.rs"));
//! ```
//!
//! Each `e2e/cases/**/*.test.luau` file becomes a Cargo test.
//!
//! # Write a scenario
//!
//! For a game where Escape opens a pause menu, save this as
//! `e2e/cases/pause.test.luau`:
//!
//! ```luau
//! local Types = require("@inslag_e2e/types")
//!
//! return {
//!     setup = function(setup: Types.Setup)
//!         setup.awaitReady()
//!     end,
//!     run = function(test: Types.Run)
//!         test.input.tapKey("Escape")
//!         test.expectEventually(function()
//!             return #test.query({ name = "PauseMenu" })
//!         end, 1, "pause menu appears")
//!     end,
//! }
//! ```
//!
//! Use `setup` to spawn fixtures, change reflected components or resources, and
//! create state trees. `run` can observe the world and send player input, but
//! cannot author entities or issue gameplay/save commands. It must advance at
//! least one frame and complete an `expect` or `expectEventually` assertion.
//!
//! `test.frames(n)` advances simulation; `test.expect(value).toEqual(expected)`
//! checks a value immediately. Read components with `test.component(entity, "Type")`
//! and resources with `test.resource("Type")`. Register reflected types in your
//! app; use full type paths if short names are ambiguous. Entity IDs are strings.
//!
//! # Set limits and run
//!
//! Create `e2e/policy.toml`:
//!
//! ```toml
//! simulation_hz = 60
//! max_frames = 10000
//! wall_timeout_seconds = 60
//! condition_timeout_frames = 300
//!
//! [frame_time]
//! p50_ms = 16.0
//! p95_ms = 2000.0
//! max_ms = 2000.0
//! ```
//!
//! Run `cargo test --test e2e`. Reports go to
//! `target/e2e/<scenario>/report.json` under the configured Cargo target directory.
//! Frame budgets measure CPU app updates, not GPU rendering. Set `E2E_POLICY` to
//! use another policy file for the whole suite.
//!
//! Name a case `*.ignored.test.luau` to opt it out of ordinary runs; use
//! `cargo test --test e2e -- --ignored` to run those cases.
