static SERIAL: Mutex<()> = Mutex::new(());

type Readiness = fn(&mut World) -> Result<bool, String>;

/// Configure the production app used by one Luau scenario.
///
/// Create a fresh suite for each call to [`run`](Self::run). Keep scenario
/// fixtures and assertions in Luau, not in the configuration callback.
pub struct Suite {
    root: PathBuf,
    configure: fn(&mut App, &Path),
    viewport: UVec2,
    readiness: Vec<Readiness>,
}

impl Suite {
    /// Use `root/assets` and `root/e2e` as the game's asset and scenario directories.
    ///
    /// `configure` adds production plugins to the headless app and receives a
    /// fresh temporary directory for writable files. Platform plugins are already
    /// installed.
    pub fn new(root: impl Into<PathBuf>, configure: fn(&mut App, &Path)) -> Self {
        Self {
            root: root.into(),
            configure,
            viewport: UVec2::new(1280, 900),
            readiness: Vec::new(),
        }
    }

    /// Set the window size used for layout and pointer input. Defaults to 1280×900.
    ///
    /// Panics if either dimension is zero.
    pub fn viewport(mut self, size: UVec2) -> Self {
        assert!(size.min_element() > 0, "viewport must be nonzero");
        self.viewport = size;
        self
    }

    /// Wait for an application-specific readiness check before calling `setup`.
    ///
    /// Return `Ok(false)` to advance another frame, `Ok(true)` when ready, or
    /// `Err(message)` to fail. All added checks and state trees must be ready;
    /// the policy's frame and wall-clock limits still apply.
    pub fn ready(mut self, check: Readiness) -> Self {
        self.readiness.push(check);
        self
    }

    /// Run a path relative to `e2e/cases`, such as `"menus/pause.test.luau"`.
    ///
    /// Requires `e2e/policy.toml` unless `E2E_POLICY` selects another file. Writes
    /// `e2e/<scenario>/report.json` beneath the Cargo target directory and panics
    /// on failure. Scenarios run serially within each process.
    pub fn run(self, path: &str) {
        run(self, path);
    }

    fn is_ready(&self, world: &mut World) -> Result<bool, String> {
        let mut ready = ecs::trees_ready(world)?;
        for check in &self.readiness {
            ready &= check(world)?;
        }
        Ok(ready)
    }
}

#[derive(Clone, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Policy {
    simulation_hz: u32,
    max_frames: u64,
    wall_timeout_seconds: u64,
    condition_timeout_frames: u64,
    frame_time: Budgets,
}

impl Policy {
    fn load(path: Option<&Path>) -> Result<Self, String> {
        let source = match path {
            Some(path) => std::fs::read_to_string(path)
                .map_err(|error| format!("read E2E policy {}: {error}", path.display()))?,
            None => include_str!("../luau/policy.toml").to_owned(),
        };
        toml::from_str(&source).map_err(|error| format!("invalid E2E policy: {error}"))
    }
}

#[derive(Clone, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Budgets {
    p50_ms: f64,
    p95_ms: Option<f64>,
    max_ms: f64,
}

#[derive(Serialize)]
struct Sample {
    frame: u64,
    milliseconds: f64,
    step: String,
}

#[derive(Serialize)]
struct Label {
    frame: u64,
    name: String,
}

#[derive(Default, Serialize)]
struct Timings {
    count: usize,
    p50_ms: f64,
    p95_ms: f64,
    p99_ms: f64,
    max_ms: f64,
}

fn timings(samples: &[Sample]) -> Timings {
    let mut values: Vec<_> = samples.iter().map(|s| s.milliseconds).collect();
    values.sort_by(f64::total_cmp);
    let percentile = |p: f64| {
        if values.is_empty() {
            0.0
        } else {
            values[((values.len() as f64 * p).ceil() as usize).saturating_sub(1)]
        }
    };
    Timings {
        count: values.len(),
        p50_ms: percentile(0.5),
        p95_ms: percentile(0.95),
        p99_ms: percentile(0.99),
        max_ms: values.last().copied().unwrap_or_default(),
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Phase {
    Bootstrap,
    Setup,
    Run,
}

struct Runner {
    suite: Suite,
    _directory: Option<tempfile::TempDir>,
    app: App,
    lua: Lua,
    phase: Phase,
    policy: Policy,
    started: Instant,
    frame: u64,
    run_start_frame: Option<u64>,
    assertions: u64,
    step: String,
    labels: Vec<Label>,
    samples: Vec<Sample>,
    setup_samples: Vec<Sample>,
    inputs: Vec<serde_json::Value>,
}

fn run(suite: Suite, path: &str) {
    let _serial = SERIAL.lock().unwrap_or_else(|e| e.into_inner());
    assert!(
        Path::new(path)
            .components()
            .all(|c| matches!(c, std::path::Component::Normal(_))),
        "scenario must be relative"
    );
    let default_policy = suite.root.join("e2e/policy.toml");
    // A process-wide override, never a scenario-specific policy exception.
    let policy_path = std::env::var_os("E2E_POLICY");
    let policy = Policy::load(Some(
        policy_path
            .as_deref()
            .map(Path::new)
            .unwrap_or(&default_policy),
    ))
    .expect("load E2E policy");
    assert!(policy.simulation_hz > 0 && policy.max_frames > 0 && policy.wall_timeout_seconds > 0);
    for limit in [
        Some(policy.frame_time.p50_ms),
        policy.frame_time.p95_ms,
        Some(policy.frame_time.max_ms),
    ]
    .into_iter()
    .flatten()
    {
        assert!(
            limit.is_finite() && limit > 0.0,
            "timing budgets must be positive and finite"
        );
    }
    let lua = Lua::new();
    lua.sandbox(true).expect("sandbox Luau");
    lua.set_memory_limit(64 * 1024 * 1024)
        .expect("limit Luau memory");
    lua.set_named_registry_value("e2e_modules", lua.create_table().unwrap())
        .unwrap();
    let started = Instant::now();
    let interrupts = Rc::new(Cell::new(0_u64));
    let counter = interrupts.clone();
    let timeout = Duration::from_secs(policy.wall_timeout_seconds);
    lua.set_interrupt(move |_| {
        counter.set(counter.get() + 1);
        if counter.get() > 100_000 || started.elapsed() > timeout {
            return Err(mlua::Error::runtime("Luau execution/time limit exceeded"));
        }
        Ok(VmState::Continue)
    });
    let directory = tempfile::tempdir().expect("isolated E2E writable directory");
    let mut app = platform::app(
        Duration::from_secs_f64(1.0 / f64::from(policy.simulation_hz)),
        &suite.root.join("assets"),
        suite.viewport,
    );
    (suite.configure)(&mut app, directory.path());
    app.finish();
    app.cleanup();
    let mut runner = Runner {
        app,
        suite,
        _directory: Some(directory),
        lua,
        phase: Phase::Bootstrap,
        policy,
        started,
        frame: 0,
        run_start_frame: None,
        assertions: 0,
        step: "bootstrap".into(),
        labels: Vec::new(),
        samples: Vec::new(),
        setup_samples: Vec::new(),
        inputs: Vec::new(),
    };
    runner.app.register_type::<KeyCode>();
    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        runner.execute(path, &interrupts)
    }))
    .unwrap_or_else(|panic| {
        Err(panic
            .downcast_ref::<String>()
            .cloned()
            .or_else(|| panic.downcast_ref::<&str>().map(|s| s.to_string()))
            .unwrap_or_else(|| "non-string panic".into()))
    });
    let report = runner.report(path, &result);
    let target = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| runner.suite.root.join("target"));
    let target = if target.is_absolute() {
        target
    } else {
        runner.suite.root.join(target)
    };
    let directory = target.join("e2e").join(path.trim_end_matches(".test.luau"));
    std::fs::create_dir_all(&directory).expect("create E2E artifact directory");
    std::fs::write(
        directory.join("report.json"),
        serde_json::to_vec_pretty(&report).unwrap(),
    )
    .expect("write E2E report");
    if let Err(error) = result {
        panic!(
            "Luau E2E {path} failed at frame {} ({:?}, step {:?}): {error}\nReport: {}",
            runner.frame,
            runner.phase,
            runner.step,
            directory.join("report.json").display()
        );
    }
}

impl Runner {
    fn check_limits(&self) -> Result<(), String> {
        if self.frame >= self.policy.max_frames {
            return Err("global frame limit exceeded".into());
        }
        if self.started.elapsed() > Duration::from_secs(self.policy.wall_timeout_seconds) {
            return Err("global wall-clock timeout exceeded".into());
        }
        Ok(())
    }

    fn advance(&mut self, count: u64) -> Result<(), String> {
        if count == 0 {
            return Err("step requires at least one frame".into());
        }
        for _ in 0..count {
            self.check_limits()?;
            let start = Instant::now();
            self.app.update();
            let elapsed = start.elapsed();
            self.frame += 1;
            let sample = Sample {
                frame: self.frame,
                milliseconds: elapsed.as_secs_f64() * 1000.0,
                step: self.step.clone(),
            };
            if self.phase == Phase::Run {
                self.samples.push(sample);
            } else {
                self.setup_samples.push(sample);
            }
        }
        Ok(())
    }

    fn execute(&mut self, path: &str, interrupts: &Cell<u64>) -> Result<(), String> {
        let root = self.suite.root.join("e2e");
        let module = load_module(&self.lua, &root, &root.join("cases").join(path)).map_err(err)?;
        let module: Table = module
            .as_table()
            .ok_or("test module must return a table")?
            .clone();
        let setup: Function = module.get("setup").map_err(err)?;
        let run: Function = module.get("run").map_err(err)?;
        // Bootstrap is readiness-driven, bounded, and separately reported.
        loop {
            self.advance(1)?;
            if self.suite.is_ready(self.app.world_mut())? {
                break;
            }
            std::thread::sleep(Duration::from_millis(1));
        }
        self.advance(3)?;
        let factory: Function = self
            .lua
            .load(include_str!("../luau/context.luau"))
            .set_name("@e2e/support/context.luau")
            .eval()
            .map_err(err)?;
        self.phase = Phase::Setup;
        self.step = "setup".into();
        let setup_context: Table = factory
            .call((false, self.policy.condition_timeout_frames))
            .map_err(err)?;
        let scene = self.call(setup, (setup_context,), interrupts)?;
        self.phase = Phase::Run;
        self.run_start_frame = Some(self.frame);
        self.step = "run".into();
        let run_context: Table = factory
            .call((true, self.policy.condition_timeout_frames))
            .map_err(err)?;
        self.call(run, (run_context, scene), interrupts)?;
        self.verify_run()
    }

    fn verify_run(&self) -> Result<(), String> {
        if self.assertions == 0 {
            return Err(
                "run() must complete at least one test.expect assertion; setup alone is not a test"
                    .into(),
            );
        }
        if self.samples.is_empty() {
            return Err("run() must exercise at least one frame".into());
        }
        let stats = timings(&self.samples);
        let limits = &self.policy.frame_time;
        let mut violations = Vec::new();
        for (name, actual, limit) in [
            ("p50", stats.p50_ms, Some(limits.p50_ms)),
            ("p95", stats.p95_ms, limits.p95_ms),
            ("max", stats.max_ms, Some(limits.max_ms)),
        ] {
            if let Some(limit) = limit
                && actual > limit
            {
                violations.push(format!("{name}: {actual:.3}ms > {limit:.3}ms"));
            }
        }
        if !violations.is_empty() {
            return Err(format!(
                "global CPU frame budget exceeded: {}",
                violations.join(", ")
            ));
        }
        Ok(())
    }

    fn call(
        &mut self,
        function: Function,
        arguments: impl mlua::IntoLuaMulti,
        interrupts: &Cell<u64>,
    ) -> Result<Value, String> {
        let thread = self.lua.create_thread(function).map_err(err)?;
        interrupts.set(0);
        let mut yielded: Value = thread.resume(arguments).map_err(err)?;
        let mut immediate = 0;
        while thread.status() != ThreadStatus::Finished {
            self.check_limits()?;
            let request = yielded.as_table().ok_or("unsupported coroutine yield")?;
            let operation: String = request.get("operation").map_err(err)?;
            let args: Table = request.get("arguments").map_err(err)?;
            immediate += 1;
            if immediate > 10000 {
                return Err("too many operations without advancing a frame".into());
            }
            let response = self
                .dispatch(&operation, &args)
                .map_err(|error| format!("operation `{operation}` failed: {error}"))?;
            if operation == "step" {
                immediate = 0;
            }
            interrupts.set(0);
            yielded = thread.resume(response).map_err(err)?;
        }
        Ok(yielded)
    }

    fn dispatch(&mut self, operation: &str, args: &Table) -> Result<Value, String> {
        // These checks are authoritative even if a script retains a setup closure
        // or constructs its own coroutine request. Run cannot return to setup.
        let setup_only = matches!(
            operation,
            "spawn"
                | "despawn"
                | "parent"
                | "insert"
                | "remove"
                | "set_resource"
                | "set_asset"
                | "copy_asset"
                | "create_tree"
        );
        if setup_only && self.phase != Phase::Setup {
            return Err(format!("{operation} is allowed only during setup()"));
        }
        if operation == "input" && !matches!(self.phase, Phase::Setup | Phase::Run) {
            return Err("input is allowed only during setup() or run()".into());
        }
        if matches!(operation, "assertion" | "label") && self.phase != Phase::Run {
            return Err(format!("{operation} is allowed only during run()"));
        }
        let world = self.app.world_mut();
        match operation {
            "copy_asset" => Ok(Value::Boolean(ecs::copy_asset(world, args)?)),
            "query" => ecs::query(world, &self.lua, args),
            "component" => ecs::read(world, &self.lua, args, false),
            "resource" => ecs::read(world, &self.lua, args, true),
            "tree" => ecs::tree(world, &self.lua, args, false),
            "screen" => ecs::screen(world, &self.lua, args),
            "ready" => Ok(Value::Boolean(self.suite.is_ready(world)?)),
            "exiting" => Ok(Value::Boolean(self.app.should_exit().is_some())),
            "save_status" => {
                let status = world
                    .get_resource::<inslag_persist::SaveStatus>()
                    .ok_or("saveStatus requires the production SavePlugin")?;
                self.lua.to_value_with(&serde_json::json!({
                    "loading": status.is_loading(),
                    "writable": status.can_save(),
                    "load_error": status.load().and_then(|result| result.as_ref().err()),
                    "save_error": status.last_save().and_then(|result| result.as_ref().err()),
                    "generation": status.last_save().and_then(|result| result.as_ref().ok()).map(|stats| stats.generation),
                }), mlua::SerializeOptions::new().serialize_none_to_null(false).serialize_unit_to_null(false)).map_err(err)
            }
            "step" => {
                let count: u64 = args.get("count").map_err(err)?;
                self.advance(count)?;
                Ok(Value::Nil)
            }
            "spawn" => {
                let mut entity = world.spawn_empty();
                if let Some(name) = args.get::<Option<String>>("name").map_err(err)? {
                    entity.insert(Name::new(name));
                }
                Ok(Value::String(
                    self.lua
                        .create_string(entity.id().to_bits().to_string())
                        .map_err(err)?,
                ))
            }
            "despawn" => {
                world
                    .get_entity_mut(ecs::entity(&args.get::<String>("entity").map_err(err)?)?)
                    .map_err(err)?
                    .despawn();
                Ok(Value::Nil)
            }
            "parent" => {
                let child = ecs::entity(&args.get::<String>("entity").map_err(err)?)?;
                let parent = ecs::entity(&args.get::<String>("parent").map_err(err)?)?;
                if child == parent || world.get_entity(parent).is_err() {
                    return Err("invalid parent".into());
                }
                let mut cursor = parent;
                for _ in 0..256 {
                    if cursor == child {
                        return Err("parent relationship would create a cycle".into());
                    }
                    match world.get::<ChildOf>(cursor) {
                        Some(p) => cursor = p.parent(),
                        None => break,
                    }
                }
                world
                    .get_entity_mut(child)
                    .map_err(err)?
                    .insert(ChildOf(parent));
                Ok(Value::Nil)
            }
            "insert" | "set_resource" => {
                ecs::write(world, &self.lua, args, operation == "set_resource")?;
                Ok(Value::Nil)
            }
            "set_asset" => ecs::write_asset(world, &self.lua, args).map(Value::Boolean),
            "remove" => {
                ecs::remove(world, args)?;
                Ok(Value::Nil)
            }
            "create_tree" => ecs::tree(world, &self.lua, args, true),
            "input" => {
                input::deliver(world, args)?;
                self.inputs.push(serde_json::json!({"frame": self.frame + 1, "step": self.step, "input": self.lua.from_value::<serde_json::Value>(Value::Table(args.clone())).map_err(err)?}));
                Ok(Value::Nil)
            }
            "assertion" => {
                self.assertions += 1;
                Ok(Value::Nil)
            }
            "label" => {
                self.step = args.get("name").map_err(err)?;
                // Labels describe the current completed frame, unlike inputs
                // which are delivered to the next update. Preserve even a final
                // label with no subsequent frame (or one followed by an error).
                self.labels.push(Label {
                    frame: self.frame,
                    name: self.step.clone(),
                });
                Ok(Value::Nil)
            }
            _ => Err(format!("unknown harness operation {operation}")),
        }
    }

    fn report(&mut self, path: &str, result: &Result<(), String>) -> serde_json::Value {
        let mut slowest: Vec<_> = self.samples.iter().collect();
        slowest.sort_by(|a, b| b.milliseconds.total_cmp(&a.milliseconds));
        slowest.truncate(10);
        let names: Vec<_> = self.app.world_mut().query::<(Entity, &Name)>().iter(self.app.world()).map(|(id, name)| serde_json::json!({"id": id.to_bits().to_string(), "name": name.as_str()})).collect();
        let state_trees = ecs::tree_snapshot(self.app.world_mut());
        serde_json::json!({
            "schema_version": 2, "scenario": path, "result": if result.is_ok() { "passed" } else { "failed" }, "error": result.as_ref().err(),
            "measurement": "renderer-free CPU app.update wall time; nearest-rank percentiles", "build_profile": if cfg!(debug_assertions) { "dev" } else { "release" },
            "policy": self.policy, "frames": self.frame, "assertions": self.assertions, "phase": format!("{:?}", self.phase), "step": self.step,
            "run_start_frame": self.run_start_frame, "labels": self.labels,
            "wall_seconds": self.started.elapsed().as_secs_f64(), "run": timings(&self.samples), "bootstrap_and_setup": timings(&self.setup_samples),
            "slowest_frames": slowest, "samples": self.samples, "inputs": self.inputs, "named_entities": names, "state_trees": state_trees,
        })
    }
}

fn load_module(lua: &Lua, root: &Path, path: &Path) -> mlua::Result<Value> {
    let root = root.canonicalize().map_err(mlua::Error::external)?;
    let path = path.canonicalize().map_err(mlua::Error::external)?;
    if !path.starts_with(&root) || path.extension().is_none_or(|e| e != "luau") {
        return Err(mlua::Error::runtime(
            "require must resolve to a .luau module beneath e2e/",
        ));
    }
    let cache: Table = lua.named_registry_value("e2e_modules")?;
    let key = path
        .to_str()
        .ok_or_else(|| mlua::Error::runtime("module path must be UTF-8"))?;
    match cache.get::<Value>(key)? {
        Value::Nil => {}
        Value::Boolean(false) => {
            return Err(mlua::Error::runtime(format!("cyclic require: {key}")));
        }
        value => return Ok(value),
    }
    cache.set(key, false)?;
    let parent = path.parent().unwrap().to_owned();
    let environment = lua.create_table()?;
    let metatable = lua.create_table()?;
    metatable.set("__index", lua.globals())?;
    environment.set_metatable(Some(metatable))?;
    environment.set(
        "require",
        lua.create_function(move |lua, name: String| {
            if name == "@inslag_e2e/types" {
                return lua
                    .load(include_str!("../luau/types.luau"))
                    .set_name("@inslag_e2e/types")
                    .eval();
            }
            load_module(lua, &root, &parent.join(name).with_extension("luau"))
        })?,
    )?;
    let source = std::fs::read_to_string(&path).map_err(mlua::Error::external)?;
    let value: Value = lua
        .load(&source)
        .set_name(format!("@{}", path.display()))
        .set_environment(environment)
        .eval()?;
    if value.is_nil() || matches!(value, Value::Boolean(false)) {
        return Err(mlua::Error::runtime(
            "modules must return a value other than nil/false",
        ));
    }
    cache.set(key, value.clone())?;
    Ok(value)
}

fn err(error: impl std::fmt::Display) -> String {
    error.to_string()
}

